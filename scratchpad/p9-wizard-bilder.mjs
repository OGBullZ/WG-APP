/* P9: Einrichtungs-Assistent — Bilder je Schritt. Ausgabe: test/shots/p9/onb-<w>x<h>-<theme>-<schritt>.png
   Aufruf: node scratchpad/p9-wizard-bilder.mjs [--w 320] [--h 640] [--theme dark|light] [--lang de|en] [--tastatur 1] (Tastatur: Höhe wie mit offener Bildschirmtastatur) */
import { chromium } from 'playwright';
import { mkdirSync } from 'fs';
import { STUB } from '../test/_fbstub.mjs';
const arg = (k, d) => (process.argv.includes(k) ? process.argv[process.argv.indexOf(k) + 1] : d);
const W = Number(arg('--w', 320)), H = Number(arg('--h', 640)), THEME = arg('--theme', 'dark'), LANG = arg('--lang', 'de');
mkdirSync('test/shots/p9', { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, serviceWorkers: 'block' });
await ctx.routeWebSocket(/./, () => {});
await ctx.route('**/*', r => (/firebasedatabase|firebaseio|vercel|googleapis/.test(r.request().url()) ? r.abort() : r.continue()));
await ctx.route(/firebase-(app|database)-compat[-\d.]*\.js/, r => r.fulfill({ status: 200, contentType: 'application/javascript', body: /firebase-app-compat/.test(r.request().url()) ? STUB : '' }));
await ctx.addInitScript(([th, l]) => { window.__wgSeed = {}; localStorage.setItem('wg_theme', JSON.stringify(th)); localStorage.setItem('wg_lang', JSON.stringify(l)); }, [THEME, LANG]);
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://127.0.0.1:8099/wgapp.html', { waitUntil: 'domcontentloaded' });
await page.locator('.tabbar').waitFor({ timeout: 30000 });
await page.evaluate(() => window.__wg.fire && window.__wg.fire());
await page.waitForTimeout(1200);
const onb = page.locator('[data-testid="onboarding"]');
const pre = `test/shots/p9/onb-${W}x${H}-${LANG}-${THEME}`;
const shot = async n => { await page.waitForTimeout(700); await page.screenshot({ path: `${pre}-${n}.png` }); };
const weiter = async () => { await page.evaluate(() => document.querySelector('.onb-step [data-testid="onb-next"]').click()); await page.waitForTimeout(700); };
await shot('1-welcome');
await onb.locator('[data-testid="onb-found"]').click();
await shot('2-people-leer');
await onb.getByLabel(LANG === 'en' ? 'Your name' : 'Dein Name', { exact: true }).fill('Lena');
await onb.getByLabel(LANG === 'en' ? 'Housemate 1' : 'Mitbewohner 1', { exact: true }).fill('Max');
await shot('2b-people');
await weiter(); await weiter(); await shot('4-mods');
await page.evaluate(() => { document.querySelector('.onb-card').scrollTop = 9999; }); await shot('4b-mods-unten');
await weiter(); await shot('5-putz');
const chip = n => onb.locator('.onb-chips button', { hasText: n });
await chip(LANG === 'en' ? 'Paper' : 'Papier').first().click();
await chip(LANG === 'en' ? 'Yellow' : 'Gelber').first().click().catch(() => {});
await shot('5b-putz-chips');
await page.evaluate(() => { document.querySelector('.onb-card').scrollTop = 9999; }); await shot('5c-putz-unten');
await weiter(); await shot('6-money');
await weiter(); await shot('7-push');
await weiter(); await shot('8-invite');
await weiter(); await shot('9-done');
if (errs.length) console.log('PAGEERROR', errs.slice(0, 3));
console.log('ok', pre);
await browser.close();
